/**
 * Tool catalog generator — the tool registry is the single source of truth.
 *
 *   bun run scripts/generate-docs.ts            # build docs-site/ (index.html + tools.json)
 *   bun run scripts/generate-docs.ts --readme   # also rewrite the README tool tables and counts
 *   bun run scripts/generate-docs.ts --check    # exit 1 if README tables/counts are stale (CI)
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { z } from "zod";
import type { MetabaseClient } from "../src/client.js";
import { buildToolCatalog, TOOLSET_PRESETS, type ToolDef } from "../src/registry.js";
import { TOOL_MODULES } from "../src/tools/index.js";
import { SERVER_VERSION } from "../src/server-info.js";

const README = "README.md";
const OUT_DIR = "docs-site";
const START = "<!-- tools:start (generated by scripts/generate-docs.ts, do not edit) -->";
const END = "<!-- tools:end -->";

// Registration never calls the API, so a stub client is enough
const catalog = buildToolCatalog({} as MetabaseClient, { metabaseUrl: "http://localhost:3000", readOnly: false });

type ToolDoc = {
  name: string;
  toolset: string;
  toolsetLabel: string;
  write: boolean;
  description: string;
  annotations: ToolDef["annotations"];
  parameters: Record<string, unknown>;
};

const docs: ToolDoc[] = catalog.map((t) => {
  let parameters: Record<string, unknown> = {};
  try {
    parameters = z.toJSONSchema(z.object(t.inputSchema as z.ZodRawShape)) as Record<string, unknown>;
    delete parameters.$schema;
  } catch {
    parameters = { note: "schema could not be rendered" };
  }
  return {
    name: t.name,
    toolset: t.toolset,
    toolsetLabel: t.toolsetLabel,
    write: t.write,
    description: t.description,
    annotations: t.annotations,
    parameters,
  };
});

const reads = docs.filter((d) => !d.write);
const writes = docs.filter((d) => d.write);

const table = (items: ToolDoc[]): string => {
  const rows = TOOL_MODULES.map((m) => {
    const names = items.filter((d) => d.toolset === m.toolset).map((d) => `\`${d.name}\``);
    return names.length ? `| **${m.label}** (\`${m.toolset}\`) | ${names.join(", ")} |` : null;
  }).filter(Boolean);
  return ["| Toolset | Tools |", "|---|---|", ...rows].join("\n");
};

const readmeSection = [
  START,
  "",
  `### Read tools (${reads.length}, always available)`,
  "",
  table(reads),
  "",
  `### Write tools (${writes.length}, hidden in read-only mode)`,
  "",
  table(writes),
  "",
  `Presets for \`METABASE_TOOLSETS\`: ${Object.entries(TOOLSET_PRESETS)
    .map(([k, v]) => `\`${k}\` (${k === "all" ? "everything" : v.join(", ")})`)
    .join("; ")}.`,
  "",
  END,
].join("\n");

const updateReadme = (text: string): string => {
  const s = text.indexOf(START.slice(0, 20));
  const e = text.indexOf(END);
  if (s === -1 || e === -1) throw new Error(`README is missing the ${START} / ${END} markers`);
  let out = text.slice(0, s) + readmeSection + text.slice(e + END.length);
  out = out.replace(/\*\*\d+ tools\*\*/g, `**${docs.length} tools**`);
  out = out.replace(
    /\*\*\d+ MCP tools\*\* across \d+ (domains|toolsets)/g,
    `**${docs.length} MCP tools** across ${TOOL_MODULES.length} toolsets`
  );
  return out;
};

const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

const paramRows = (schema: Record<string, unknown>): string => {
  const props = (schema.properties ?? {}) as Record<string, any>;
  const required = new Set((schema.required ?? []) as string[]);
  const keys = Object.keys(props);
  if (!keys.length) return `<p class="muted">No parameters.</p>`;
  return `<table><thead><tr><th>Parameter</th><th>Type</th><th>Description</th></tr></thead><tbody>${keys
    .map((k) => {
      const p = props[k];
      const type = p.type ?? (p.enum ? "enum" : p.anyOf ? "union" : "object");
      const enumPart = p.enum ? ` <span class="muted">(${p.enum.map((v: unknown) => esc(String(v))).join(" | ")})</span>` : "";
      return `<tr><td><code>${esc(k)}</code>${required.has(k) ? ' <span class="req">required</span>' : ""}</td><td>${esc(
        String(type)
      )}${enumPart}</td><td>${esc(p.description ?? "")}</td></tr>`;
    })
    .join("")}</tbody></table>`;
};

const badges = (d: ToolDoc) =>
  [
    d.write ? `<span class="b w">write</span>` : `<span class="b r">read</span>`,
    d.annotations.destructiveHint ? `<span class="b d">destructive</span>` : "",
    d.annotations.idempotentHint && d.write ? `<span class="b">idempotent</span>` : "",
  ].join("");

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Metabase MCP tool catalog</title>
<meta name="description" content="All ${docs.length} tools of @serdnaley/metabase-mcp, the headless MCP server for Metabase: API-key auth, stdio and HTTP, every Metabase tier.">
<style>
:root{--bg:#fff;--fg:#1d2433;--muted:#6b7385;--card:#f6f7f9;--line:#e3e6eb;--accent:#509ee3;--w:#c2410c;--d:#b91c1c;--r:#15803d}
@media (prefers-color-scheme:dark){:root{--bg:#12151b;--fg:#e6e9ef;--muted:#9aa3b2;--card:#1b1f27;--line:#2a303b;--accent:#6cb4f0;--w:#fb923c;--d:#f87171;--r:#4ade80}}
*{box-sizing:border-box}body{margin:0;background:var(--bg);color:var(--fg);font:15px/1.5 system-ui,-apple-system,Segoe UI,sans-serif}
main{max-width:980px;margin:0 auto;padding:24px 16px 64px}h1{margin:0 0 4px;font-size:28px}a{color:var(--accent)}
.muted{color:var(--muted)}.bar{position:sticky;top:0;background:var(--bg);padding:12px 0;border-bottom:1px solid var(--line);z-index:1}
input{width:100%;padding:10px 12px;border:1px solid var(--line);border-radius:8px;background:var(--card);color:var(--fg);font-size:15px}
.chips{display:flex;flex-wrap:wrap;gap:6px;margin-top:10px}.chip{border:1px solid var(--line);background:none;color:var(--fg);border-radius:999px;padding:3px 10px;cursor:pointer;font-size:13px}
.chip.on{background:var(--accent);border-color:var(--accent);color:#fff}
.tool{background:var(--card);border:1px solid var(--line);border-radius:10px;padding:14px 16px;margin-top:12px}
.tool h3{margin:0;font:600 15px ui-monospace,SFMono-Regular,Menlo,monospace;display:flex;flex-wrap:wrap;gap:8px;align-items:center}
.b{font:600 11px system-ui;border:1px solid var(--line);border-radius:4px;padding:1px 6px;color:var(--muted)}.b.r{color:var(--r)}.b.w{color:var(--w)}.b.d{color:var(--d)}
.ts{margin-left:auto;font:13px system-ui;color:var(--muted)}table{width:100%;border-collapse:collapse;margin-top:8px;font-size:13px}
th,td{text-align:left;padding:5px 6px;border-top:1px solid var(--line);vertical-align:top}th{color:var(--muted);font-weight:600}.req{color:var(--w);font-size:11px}
code{font-family:ui-monospace,SFMono-Regular,Menlo,monospace}
</style>
</head>
<body><main>
<h1>Metabase MCP tool catalog</h1>
<p class="muted">@serdnaley/metabase-mcp ${esc(SERVER_VERSION)}: ${docs.length} tools (${reads.length} read, ${writes.length} write) in ${TOOL_MODULES.length} toolsets.
Headless: API key auth, stdio or HTTP, every Metabase tier. <a href="https://github.com/Serdnaley/metabase-mcp">GitHub</a> · <a href="https://www.npmjs.com/package/@serdnaley/metabase-mcp">npm</a> · <a href="tools.json">tools.json</a></p>
<div class="bar"><input id="q" type="search" placeholder="Search tools, e.g. dashboard, permissions, export" aria-label="Search tools">
<div class="chips" id="chips"><button class="chip on" data-ts="">all</button>${TOOL_MODULES.map(
  (m) => `<button class="chip" data-ts="${m.toolset}">${esc(m.label)}</button>`
).join("")}</div></div>
<div id="list">${docs
  .map(
    (d) => `<section class="tool" data-ts="${d.toolset}" data-text="${esc(
      `${d.name} ${d.description} ${d.toolsetLabel}`.toLowerCase()
    )}"><h3 id="${d.name}">${esc(d.name)}${badges(d)}<span class="ts">${esc(d.toolsetLabel)}</span></h3><p>${esc(
      d.description
    )}</p>${paramRows(d.parameters)}</section>`
  )
  .join("\n")}</div>
<p class="muted" id="empty" hidden>No tools match.</p>
</main>
<script>
const q=document.getElementById('q'),chips=[...document.querySelectorAll('.chip')],tools=[...document.querySelectorAll('.tool')];let ts='';
function apply(){const t=q.value.trim().toLowerCase();let n=0;for(const el of tools){const ok=(!ts||el.dataset.ts===ts)&&(!t||el.dataset.text.includes(t));el.hidden=!ok;if(ok)n++}document.getElementById('empty').hidden=n>0}
q.addEventListener('input',apply);chips.forEach(c=>c.addEventListener('click',()=>{chips.forEach(x=>x.classList.remove('on'));c.classList.add('on');ts=c.dataset.ts;apply()}));
</script>
</body></html>
`;

const args = new Set(process.argv.slice(2));
const readme = readFileSync(README, "utf8");

if (args.has("--check")) {
  if (updateReadme(readme) !== readme) {
    console.error("README tool tables/counts are stale. Run: bun run docs:readme");
    process.exit(1);
  }
  console.log(`README is in sync with the registry (${docs.length} tools).`);
} else {
  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(`${OUT_DIR}/index.html`, html);
  writeFileSync(`${OUT_DIR}/tools.json`, JSON.stringify({ version: SERVER_VERSION, tools: docs }, null, 2));
  console.log(`Wrote ${OUT_DIR}/index.html and tools.json (${docs.length} tools)`);
  if (args.has("--readme")) {
    writeFileSync(README, updateReadme(readme));
    console.log("Updated README tool tables and counts");
  }
}
